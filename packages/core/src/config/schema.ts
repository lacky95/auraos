/**
 * The one typed field model of AuraOS (D108 decision 6, D36): a small JSON
 * Schema subset that a form renders and the kernel validates writes against.
 *
 * Two users, one model:
 *   - a runtime's settings schema (ARI §2.1 `settingsSchema`; Settings →
 *     Runtimes): `SettingsField`, the original subset, re-exported unchanged
 *     by runtimes/settingsSchema.ts;
 *   - an app's setup fields (manifest `setup.fields`, D108): `ConfigField`,
 *     the same field types plus `secret`, `required`, `scope`, `pattern` and
 *     a `when` condition (equality / `in` only: no expressions, no `$ref`, no
 *     if-then).
 *
 * Foundation leaf: it imports nothing of core at runtime (zod only), so the
 * manifest schema (types/), the runtimes and the setup module share it.
 */
import { z } from 'zod';

// ── the field types ─────────────────────────────────────────────────────────

/** A scalar a `when` condition compares with. */
export type ConditionValue = string | number | boolean;

/**
 * When a field (or a requirement) exists at all. Evaluated on the desired
 * values after every merge (D108 §2.4 rule 5); a field whose condition is
 * false does not exist (not asked, not validated, not delivered).
 *   { field, equals }   another field's value equals this
 *   { field, in }       another field's value is one of these
 *   { profile }         the selected operating profile is one of these
 */
export type FieldCondition =
  | { field: string; equals: ConditionValue }
  | { field: string; in: ConditionValue[] }
  | { profile: string[] };

/** Where a value is kept: once per installation (default), or per user of a per-user instance. */
export type FieldScope = 'installation' | 'user';

/** Where a secret comes from: generated by the vault, picked from the vault, or typed by the owner. */
export type SecretSource = 'generate' | 'vault' | 'ask';

interface FieldCommon {
  title: string;
  description?: string;
}

/** The runtime settings subset (ARI §2.1): unchanged since the ARI release. */
export type SettingsField =
  | (FieldCommon & { type: 'boolean'; default?: boolean })
  | (FieldCommon & { type: 'integer'; default?: number; minimum?: number; maximum?: number })
  | (FieldCommon & { type: 'string'; default?: string; enum?: string[]; enumTitles?: Record<string, string> })
  | (FieldCommon & { type: 'array'; items: { type: 'string' }; default?: string[] });

export interface SettingsSchema {
  type: 'object';
  properties: Record<string, SettingsField>;
}

interface ConfigCommon extends FieldCommon {
  /** A value must exist (after defaults) for the setup to complete. Default false. */
  required?: boolean;
  /** Default `installation`. */
  scope?: FieldScope;
  when?: FieldCondition;
}

/**
 * An app setup field (manifest `setup.fields.<name>`). `secret` fields hold
 * no value anywhere: the desired record keeps a D56 vault handle, the app
 * reads the value server-side with `credentials.get(handle)`.
 */
export type ConfigField =
  | (ConfigCommon & { type: 'boolean'; default?: boolean })
  | (ConfigCommon & { type: 'integer'; default?: number; minimum?: number; maximum?: number })
  | (ConfigCommon & { type: 'string'; default?: string; enum?: string[]; enumTitles?: Record<string, string>; pattern?: string })
  | (ConfigCommon & { type: 'array'; items?: { type: 'string' }; default?: string[] })
  | (ConfigCommon & { type: 'secret'; secret: { source: SecretSource; length?: number } });

export type ConfigFieldType = ConfigField['type'];
export const CONFIG_FIELD_TYPES = ['boolean', 'integer', 'string', 'array', 'secret'] as const satisfies readonly ConfigFieldType[];

/** A plain (non-secret) field value. */
export type ConfigValue = boolean | number | string | string[];
export type ConfigValues = Record<string, ConfigValue>;

// ── zod (the manifest's view of the same model) ─────────────────────────────

/** Field names: what an env reference, a `when` and a CLI `--values` file name. */
export const FIELD_NAME_RE = /^[a-zA-Z][a-zA-Z0-9_]{0,63}$/;

/** Longest `pattern` a field may declare. */
export const MAX_FIELD_PATTERN = 256;

/**
 * A `pattern` the kernel may evaluate on untrusted input: it compiles, is
 * short, and has no quantified group that itself contains a quantifier (the
 * shape of catastrophic backtracking, e.g. `(a+)+`). Node has no regex
 * timeout, so a pattern that could hang the kernel is refused at parse time.
 */
export function safeFieldPattern(pattern: string): boolean {
  if (pattern.length === 0 || pattern.length > MAX_FIELD_PATTERN) return false;
  try { new RegExp(pattern, 'u'); } catch { return false; }
  // A group with a quantifier inside, followed by a quantifier.
  return !/\((?:[^()\\]|\\.)*[*+}?](?:[^()\\]|\\.)*\)\s*[*+{?]/.test(pattern);
}

const conditionValue = z.union([z.string(), z.number(), z.boolean()]);
export const FieldConditionSchema: z.ZodType<FieldCondition> = z.union([
  z.object({ field: z.string().regex(FIELD_NAME_RE), equals: conditionValue }).strict(),
  z.object({ field: z.string().regex(FIELD_NAME_RE), in: z.array(conditionValue).min(1) }).strict(),
  z.object({ profile: z.array(z.string().min(1)).min(1) }).strict(),
]);

const common = {
  title: z.string().min(1).max(120),
  description: z.string().max(1000).optional(),
  required: z.boolean().optional(),
  scope: z.enum(['installation', 'user']).optional(),
  when: FieldConditionSchema.optional(),
};

export const ConfigFieldSchema: z.ZodType<ConfigField> = z.discriminatedUnion('type', [
  z.object({ ...common, type: z.literal('boolean'), default: z.boolean().optional() }).strict(),
  z.object({
    ...common, type: z.literal('integer'), default: z.number().int().optional(),
    minimum: z.number().int().optional(), maximum: z.number().int().optional(),
  }).strict(),
  z.object({
    ...common, type: z.literal('string'), default: z.string().max(4096).optional(),
    enum: z.array(z.string()).min(1).optional(), enumTitles: z.record(z.string(), z.string()).optional(),
    pattern: z.string().refine(safeFieldPattern, { message: `pattern must compile, be at most ${MAX_FIELD_PATTERN} characters and have no nested quantifier` }).optional(),
  }).strict(),
  z.object({
    ...common, type: z.literal('array'), items: z.object({ type: z.literal('string') }).strict().optional(),
    default: z.array(z.string()).optional(),
  }).strict(),
  z.object({
    ...common, type: z.literal('secret'),
    secret: z.object({ source: z.enum(['generate', 'vault', 'ask']), length: z.number().int().min(16).max(256).optional() }).strict(),
  }).strict(),
]).superRefine((f, ctx) => {
  if (f.type === 'secret' && f.secret.length !== undefined && f.secret.source !== 'generate') {
    ctx.addIssue({ code: z.ZodIssueCode.custom, path: ['secret', 'length'], message: 'secret.length applies to generated secrets only' });
  }
  if (f.type !== 'secret' && f.default !== undefined && fieldValue(f, f.default) === undefined) {
    ctx.addIssue({ code: z.ZodIssueCode.custom, path: ['default'], message: 'default does not satisfy the field\'s own constraints' });
  }
}) as z.ZodType<ConfigField>;

/**
 * A profile's view of a field (D108 §2.4 rule 4): either a new field (a
 * complete `ConfigField`) or a tightening of a base field by name (`required:
 * true`, an `enum` subset, a narrower `minimum`/`maximum`). Which one is
 * decided against the base fields (`tightenField`), never loosened.
 */
export type ConfigFieldPatch = Partial<Omit<ConfigCommon, 'title'>> & {
  type?: ConfigFieldType; title?: string; enum?: string[]; minimum?: number; maximum?: number;
};

export const ConfigFieldPatchSchema: z.ZodType<ConfigFieldPatch | ConfigField> = z.union([
  ConfigFieldSchema,
  z.object({
    required: z.literal(true).optional(),
    enum: z.array(z.string()).min(1).optional(),
    minimum: z.number().int().optional(),
    maximum: z.number().int().optional(),
    description: z.string().max(1000).optional(),
  }).strict(),
]);

// ── values ──────────────────────────────────────────────────────────────────

/** One field's value from untrusted input (form strings included), or undefined when invalid. Secrets have no value. */
export function fieldValue(f: SettingsField | ConfigField, raw: unknown): ConfigValue | undefined {
  switch (f.type) {
    case 'boolean':
      if (typeof raw === 'boolean') return raw;
      if (raw === 'true' || raw === 'false') return raw === 'true';
      return undefined;
    case 'integer': {
      const n = typeof raw === 'number' ? raw : typeof raw === 'string' && /^-?\d+$/.test(raw.trim()) ? Number(raw) : NaN;
      if (!Number.isInteger(n)) return undefined;
      if ((f.minimum !== undefined && n < f.minimum) || (f.maximum !== undefined && n > f.maximum)) return undefined;
      return n;
    }
    case 'string': {
      if (typeof raw !== 'string') return undefined;
      if (f.enum && !f.enum.includes(raw)) return undefined;
      const pattern = 'pattern' in f ? f.pattern : undefined;
      if (pattern !== undefined && (raw.length > 4096 || !safeFieldPattern(pattern) || !new RegExp(`^(?:${pattern})$`, 'u').test(raw))) return undefined;
      return raw;
    }
    case 'array': {
      const list = typeof raw === 'string' ? raw.split(',').map((s) => s.trim()).filter(Boolean) : raw;
      return Array.isArray(list) && list.every((s) => typeof s === 'string') ? list : undefined;
    }
    case 'secret':
      return undefined;
  }
}

/** Every field at its default (secrets have none). */
export function fieldDefaults(fields: Record<string, SettingsField | ConfigField>): ConfigValues {
  const out: ConfigValues = {};
  for (const [k, f] of Object.entries(fields)) if (f.type !== 'secret' && f.default !== undefined) out[k] = f.default;
  return out;
}

/** Why one value is invalid, in plain words (no value echoed). */
export function fieldProblem(f: SettingsField | ConfigField): string {
  switch (f.type) {
    case 'string': return f.enum ? `one of: ${f.enum.join(', ')}` : ('pattern' in f && f.pattern ? 'text matching the field\'s pattern' : 'text');
    case 'integer': return `a whole number${f.minimum !== undefined ? ` ≥ ${f.minimum}` : ''}${f.maximum !== undefined ? ` ≤ ${f.maximum}` : ''}`;
    case 'boolean': return 'true or false';
    case 'array': return 'a list of text';
    case 'secret': return 'a vault handle, never a value';
  }
}

/** Does a `when` condition hold for these values and this profile? A missing field compares as absent (false). */
export function conditionHolds(when: FieldCondition | undefined, values: Readonly<Record<string, unknown>>, profile: string | null): boolean {
  if (!when) return true;
  if ('profile' in when) return profile !== null && when.profile.includes(profile);
  const v = values[when.field];
  if (v === undefined || v === null || Array.isArray(v)) return false;
  return 'equals' in when ? v === when.equals : when.in.includes(v as ConditionValue);
}

/** The result of checking untrusted values against fields: the clean values and one message per bad field. */
export interface ConfigCheck {
  values: ConfigValues;
  /** field → why (never the value). Unknown keys appear under their own name. */
  fieldErrors: Record<string, string>;
  /** Required non-secret fields that have no value (after defaults). */
  missing: string[];
}

/**
 * Untrusted values against a set of (already active) fields: known keys
 * only, each valid, defaults filled, required ones present. Secret fields
 * are skipped (they hold handles, checked by the vault). Never throws.
 */
export function checkConfigValues(fields: Record<string, ConfigField>, input: unknown): ConfigCheck {
  const fieldErrors: Record<string, string> = {};
  const values = fieldDefaults(fields);
  if (!input || typeof input !== 'object' || Array.isArray(input)) {
    return { values, fieldErrors: { '': 'values must be an object' }, missing: [] };
  }
  for (const [k, raw] of Object.entries(input as Record<string, unknown>)) {
    const f = fields[k];
    if (!f) { fieldErrors[k] = 'unknown field'; continue; }
    if (f.type === 'secret') { fieldErrors[k] = 'a secret field takes a vault handle, never a value'; continue; }
    const v = fieldValue(f, raw);
    if (v === undefined) fieldErrors[k] = `invalid value (${fieldProblem(f)})`;
    else values[k] = v;
  }
  const missing = Object.entries(fields)
    .filter(([k, f]) => f.type !== 'secret' && f.required === true && values[k] === undefined && !(k in fieldErrors))
    .map(([k]) => k);
  return { values, fieldErrors, missing };
}
